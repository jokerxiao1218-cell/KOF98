def _part(name, pal_id, pal):
    """部件 Surface 缓存(同部件同配色只画一次)。"""
    key = (name, pal_id)
    if key not in _part_cache:
        _part_cache[key] = paint(name, PARTS[name], pal)
    return _part_cache[key]
